import { chromium } from 'playwright';
import fs from 'node:fs/promises';
await fs.mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => {
  if (m.type() === 'error') errors.push(m.text());
});
await page.goto('http://localhost:4173/');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'artifacts/menu.png' });
await page.getByRole('button', { name: /Begin your journey/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: 'artifacts/intro.png' });
await page.getByRole('button', { name: /Carry the spark/ }).click();
await page.waitForTimeout(7000);
await page.keyboard.down('KeyD');
await page.waitForTimeout(2000);
await page.keyboard.up('KeyD');
await page.screenshot({ path: 'artifacts/playing.png' });
console.log('STATE', await page.evaluate(() => window.NOVAKI_QA.state()));
await page.evaluate(() => window.NOVAKI_QA.addXp(20));
await page.waitForTimeout(300);
await page.screenshot({ path: 'artifacts/levelup.png' });
console.log('ERRORS', errors);
await browser.close();
